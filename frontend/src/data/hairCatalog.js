export function getHairProducts() {
  return HAIR_CATALOG.map(withTier);
}

export function findHairProduct(id) {
  const p = HAIR_CATALOG.find((item) => item.id === id);
  return p ? withTier(p) : null;
}

export function filterHairProducts({ search, category }) {
  let list = HAIR_CATALOG.map(withTier);
  if (category && category !== 'hair') return [];
  if (search) {
    const q = search.toLowerCase();
    list = list.filter(
      (p) =>
        p.name.toLowerCase().includes(q) ||
        (p.description && p.description.toLowerCase().includes(q))
    );
  }
  return list;
}

export function isInquiryProduct(product) {
  if (!product) return false;
  return Boolean(product.price_on_inquiry) || String(product.id).startsWith('hair-');
}
